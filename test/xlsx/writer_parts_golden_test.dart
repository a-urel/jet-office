// No @TestOn: this file runs on the VM and in Chrome against the same
// constants, so it also extends decision 0006's check (the contents of every
// part are identical on both platforms) to every fixture.
//
// The constants pin the contents of every part the writer produces for every
// fixture of `allFixtures()`. They were computed on the writer before the
// cell encoder gained the workbook model's entry points, so a change to the
// writer's output fails here. A deliberate change to the writer's output
// updates them, with the reason in the commit.
import 'package:test/test.dart';

import '../fixtures/fixtures.dart';
import '../support/fnv1a.dart';
import '../support/read_xlsx.dart';

void main() {
  for (final Fixture fixture in allFixtures()) {
    test('${fixture.name} writes the pinned part contents', () {
      final Map<String, int> sums = <String, int>{
        for (final MapEntry<String, List<int>> e in readXlsxBytes(
          fixture.build(),
        ).entries)
          e.key: fnv1a(e.value),
      };
      expect(sums, _pinned[fixture.name]);
    });
  }

  test('every fixture has pinned part contents', () {
    expect(
      _pinned.keys.toSet(),
      allFixtures().map((Fixture f) => f.name).toSet(),
    );
  });
}

