/// The parts of a new document: Word for Mac's blank document, as constants.
///
/// Not ported from Quds; written for jet_office. The theme, styles, font
/// table, settings and web settings XML below are taken from a blank
/// document saved by Microsoft Word for Mac 16.114.1 (build 16.114.26102031)
/// and kept in `test/fixtures/owner/docx/blank.docx`. Removed from them:
/// the revision identifiers (`w:rsid*`, `w:rsids`), the document ids
/// (`w14:docId`, `w15:docId`), `w:proofState`, `w:attachedTemplate`, the
/// document properties (`docProps/`), and the regional settings of the
/// machine that saved the file. Those are written as Word's US defaults:
/// `w:themeFontLang` and every `w:lang` are `en-US` (with `w:eastAsia`
/// `en-US` and `w:bidi` `ar-SA`), and `w:decimalSymbol` and
/// `w:listSeparator` are left out so that Word uses the reader's system
/// values. The style ids and the names of the linked
/// character styles (`Balk1` and `Başlık 1 Char`, say) and the theme's name
/// are Word's en-US ones (`Heading1`, `Heading 1 Char`, `Office Theme`). `w:compatSetting compatibilityMode` 15 is kept, so Word does not
/// open the file in compatibility mode.
///
/// The section is A4 portrait (`w:pgSz` 11906 by 16838 twips) with the
/// margins, header and footer distances and document grid of that file
/// (spec 4.5). `blank.docx` is A4, so the Letter fallback did not apply.
///
/// Whether Word's theme and style XML may ship in an Apache-2.0 package is
/// an open question for the owner (`NOTICE`); the fallback is the ECMA-376
/// default theme with hand-written styles of the same values.
library;

